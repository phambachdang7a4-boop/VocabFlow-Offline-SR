const assert = require('node:assert/strict');
const { mkdtempSync, rmSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { createRepository, srs } = require('./test-support.cjs');

const original = srs.initialProgress('2026-01-01');
const frozen = srs.freezeProgress(original);
assert.equal(frozen.frozen, true);
assert.equal(frozen.nextReviewOn, null);
assert.equal(srs.isDue(frozen, '2029-01-01'), false, 'Frozen words never become due');
assert.equal(srs.isDue({ ...frozen, nextReviewOn: '2026-01-01' }, '2029-01-01'), false, 'The flag itself excludes even stale due dates');
assert.equal(srs.rescheduleProgress(frozen).nextReviewOn, null);
assert.deepEqual(original, srs.initialProgress('2026-01-01'), 'Freeze is pure');
assert.throws(() => srs.applyReview(frozen, true, '2026-01-01'), /chưa đến hạn/);
const resumedEarly = srs.unfreezeProgress(frozen, '2026-01-10');
assert.equal(resumedEarly.level, 6);
assert.equal(resumedEarly.nextReviewOn, '2026-01-31');
assert.equal(srs.isDue(resumedEarly, '2026-01-10'), false);
const resumedLate = srs.unfreezeProgress(frozen, '2026-02-01');
assert.equal(resumedLate.nextReviewOn, '2026-02-01');
assert.equal(srs.isDue(resumedLate, '2026-02-01'), true);
const resumedSameDay = srs.unfreezeProgress({ ...frozen, lastReviewedOn: '2026-02-01', reviewCount: 4 }, '2026-02-01');
assert.equal(resumedSameDay.nextReviewOn, '2026-02-02');
assert.equal(resumedSameDay.reviewCount, 4);
assert.equal(resumedSameDay.learnedOn, '2026-01-01');

const root = mkdtempSync(join(tmpdir(), 'vocabflow-freeze-'));
let harness = createRepository(root);

(async () => {
  let { repo } = harness;
  const input = { term: 'freeze-test', meaning: 'kiểm tra đóng băng', ipa: '', note: 'giữ ghi chú', example: '' };
  await repo.saveWord(input);
  const [word] = await repo.listWords();
  assert.equal(word.frozen, false);
  const beforeCount = (await repo.listWords()).length;
  await repo.setWordFrozen(word.id, true);
  let [saved] = await repo.listWords();
  assert.equal(saved.frozen, true);
  assert.equal(saved.level, word.level);
  assert.equal(saved.reviewCount, 0, 'Freeze is not an answer');
  assert.equal(saved.note, input.note);
  assert.equal(saved.createdAt, word.createdAt);
  assert.equal((await repo.listWords()).length, beforeCount, 'Frozen words still count towards storage limit');
  await assert.rejects(repo.recordReview(word.id, true, 0), /đóng băng/);
  await repo.setWordFrozen(word.id, true);
  assert.equal((await repo.listWords())[0].level, 1, 'Repeated freeze is idempotent');
  await repo.saveWord({ ...input, meaning: 'nghĩa đã sửa' }, word.id);
  assert.equal((await repo.listWords())[0].frozen, true, 'Editing does not unfreeze');
  harness.db.close();
  harness = createRepository(root);
  repo = harness.repo;
  [saved] = await repo.listWords();
  assert.equal(saved.frozen, true, 'Frozen flag survives closing and reopening the database');
  assert.equal(saved.meaning, 'nghĩa đã sửa');
  harness.setDay('2026-01-10');
  await repo.setWordFrozen(word.id, false);
  [saved] = await repo.listWords();
  assert.equal(saved.frozen, false);
  assert.equal(saved.completed, false);
  assert.equal(saved.level, 6);
  assert.equal(saved.nextReviewOn, '2026-01-31');
  assert.equal(saved.learnedOn, '2026-01-01');
  assert.equal(saved.reviewCount, 0);
  await repo.setWordFrozen(word.id, false);
  assert.equal((await repo.listWords())[0].level, 6);
  await assert.rejects(repo.recordReview(word.id, true, 0), /chưa đến hạn/);
  await repo.setWordFrozen(word.id, true);
  harness.setDay('2026-02-01');
  await repo.setWordFrozen(word.id, false);
  [saved] = await repo.listWords();
  assert.equal(saved.level, 6);
  assert.equal(saved.nextReviewOn, '2026-02-01');
  await repo.recordReview(word.id, false, 0);
  [saved] = await repo.listWords();
  assert.equal(saved.level, 5, 'Resume still follows the one-level failure rule');
  const count = saved.reviewCount;
  await repo.setWordFrozen(word.id, true);
  await repo.setWordFrozen(word.id, false);
  [saved] = await repo.listWords();
  assert.equal(saved.level, 6);
  assert.equal(saved.nextReviewOn, '2026-02-02');
  assert.equal(saved.reviewCount, count);

  // Emulate an actual previous (v3) schema to verify additive migration.
  harness.db.exec('ALTER TABLE word_progress DROP COLUMN frozen; PRAGMA user_version = 3;');
  harness.db.close();
  harness = createRepository(root);
  repo = harness.repo;
  const [migrated] = await repo.listWords();
  assert.equal(migrated.frozen, false);
  assert.equal(migrated.level, saved.level);
  assert.equal(migrated.reviewCount, saved.reviewCount);
  assert.equal(migrated.nextReviewOn, saved.nextReviewOn);
  assert.equal(migrated.meaning, saved.meaning);
  assert.equal(harness.db.prepare('PRAGMA user_version').get().user_version, 4);
  await assert.rejects(repo.setWordFrozen(999, true), /không còn tồn tại/);
  await assert.rejects(repo.setWordFrozen(-1, true), /không hợp lệ/);
  await repo.setWordFrozen(word.id, true);
  await repo.deleteWord(word.id);
  assert.equal((await repo.listWords()).length, 0);
  assert.equal(harness.db.prepare('SELECT COUNT(*) AS n FROM word_progress').get().n, 0);
  console.log('PASS: frozen exclusion, permanent pause, search/edit retention, total count, persistent freeze, unfreeze to level 6, resume dates, same-day protection, migration, deletion.');
})().catch(error => {
  console.error(error);
  process.exitCode = 1;
}).finally(() => {
  try { harness.db?.close(); } catch {}
  rmSync(root, { recursive: true, force: true });
});
